"""
Correct the shear-compression benchmark mesh to the GEOS reference geometry.

Why this exists
---------------
`single_fracture_under_shear_compression_mesh.e`, as generated by
`single_fracture_under_shear_compression_mesh.jou`, places the fracture between
(-0.9125, -0.405) and (+0.9125, +0.405).  That is a straight, conforming
fracture, but it sits at

    psi = 23.93335 deg,   b = 0.998339 m

whereas the GEOS validation case this benchmark reproduces — and every
`*_analytic` postprocessor in the four decks — specifies

    psi = 20.0 deg,       b = 1.0 m

The consequence was a 36 % error in the reported normal stress (sigma_n =
-sigma sin^2 psi is pure statics, so nothing else can explain it) and an
apparent 4 % error in the slip that was being attributed to discretization.
Against the correct geometry the interface laws agree with the closed form to
about 0.1 %.

What this script does
---------------------
Applies the anisotropic scaling that maps the meshed fracture onto the GEOS
one:

    a = cos(20 deg) / 0.9125 = 1.0298...        (x)
    c = sin(20 deg) / 0.405  = 0.84449...       (y)

which sends the fracture tip (0.9125, 0.405) to (cos 20, sin 20), i.e. exactly
psi = 20 deg and b = 1.

A scaling is a linear map, so it takes quads to quads, keeps the fracture
straight and conforming, keeps it through the origin, and leaves connectivity,
blocks, nodesets and sidesets untouched.  Only the node coordinates change.

The cost is that the outer box is no longer square: 82.384 m x 67.560 m instead
of 80 m x 80 m.  Relative to a 2 m fracture both are "far field", but the
domain is 16 % tighter in y than GEOS's, so the finite-domain part of the
residual error is not identical to theirs.  That is recorded rather than hidden.

Rebuilding from Cubit instead
-----------------------------
If Cubit is available, the cleaner fix is to correct the journal file directly:
change the webcut offsets from 0.9125 / 0.405 to

    xplane offset 0.93969262078591   (cos 20 deg)
    yplane offset 0.34202014332567   (sin 20 deg)

and regenerate.  `single_fracture_under_shear_compression_mesh.jou` carries
those values as of 2026-09-02.  This script exists because Cubit is not
available on every machine that needs to run the benchmark, and because the
6.4 MB Exodus file is too large to keep in git.

Usage
-----
    python correct_inclination.py            # writes the _psi20 mesh
    python correct_inclination.py --check    # verify an existing output only

Requires numpy and netCDF4.
"""

import argparse
import math
import os
import shutil
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "single_fracture_under_shear_compression_mesh.e")
TARGET = os.path.join(HERE, "single_fracture_under_shear_compression_mesh_psi20.e")

# The geometry the Cubit journal actually produced.
SOURCE_TIP_X = 0.9125
SOURCE_TIP_Y = 0.405

# The GEOS reference geometry.
TARGET_PSI_DEG = 20.0
TARGET_HALF_LENGTH = 1.0

FRACTURE_NODESET = "fracture_interface"


def scale_factors():
    """(a, c) mapping the meshed fracture tip onto the GEOS one."""
    psi = math.radians(TARGET_PSI_DEG)
    a = TARGET_HALF_LENGTH * math.cos(psi) / SOURCE_TIP_X
    c = TARGET_HALF_LENGTH * math.sin(psi) / SOURCE_TIP_Y
    return a, c


def nodeset_names(ds):
    """Exodus pads name records with NULs; masking must be off to see them."""
    ds.set_auto_mask(False)
    return [
        b"".join(row).split(b"\x00")[0].decode().strip()
        for row in ds.variables["ns_names"][:]
    ]


def measure(path):
    """Return (psi_deg, half_length, xrange, yrange, collinearity_residual)."""
    import netCDF4

    with netCDF4.Dataset(path) as ds:
        names = nodeset_names(ds)
        idx = names.index(FRACTURE_NODESET) + 1
        nodes = ds.variables[f"node_ns{idx}"][:] - 1
        x = np.asarray(ds.variables["coordx"][:])
        y = np.asarray(ds.variables["coordy"][:])
        fx, fy = x[nodes], y[nodes]

    slope, intercept = np.polyfit(fx, fy, 1)
    resid = float(np.max(np.abs(fy - np.polyval([slope, intercept], fx))))
    psi = math.degrees(math.atan(abs(slope)))
    half = 0.5 * math.hypot(fx.max() - fx.min(), fy.max() - fy.min())
    return psi, half, (x.min(), x.max()), (y.min(), y.max()), resid


def apply_scaling(source, target):
    import netCDF4

    a, c = scale_factors()
    shutil.copyfile(source, target)
    with netCDF4.Dataset(target, "a") as ds:
        ds.variables["coordx"][:] = np.asarray(ds.variables["coordx"][:]) * a
        ds.variables["coordy"][:] = np.asarray(ds.variables["coordy"][:]) * c
    return a, c


def report(path, label):
    psi, half, xr, yr, resid = measure(path)
    print(f"  {label}")
    print(f"    psi            = {psi:.6f} deg")
    print(f"    half-length b  = {half:.9f} m")
    print(f"    domain         = {xr[1]-xr[0]:.4f} x {yr[1]-yr[0]:.4f} m")
    print(f"    max deviation of fracture nodes from a straight line = {resid:.2e} m")
    return psi, half


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument(
        "--check", action="store_true", help="only verify an existing output mesh"
    )
    args = parser.parse_args(argv)

    try:
        import netCDF4  # noqa: F401
    except ImportError:
        print(
            "netCDF4 is required.  Try the `moose` environment:\n"
            "  /home/geomechanics/miniforge/envs/moose/bin/python correct_inclination.py",
            file=sys.stderr,
        )
        return 1

    if args.check:
        if not os.path.exists(TARGET):
            print(f"{TARGET} does not exist; run without --check first.", file=sys.stderr)
            return 1
        report(TARGET, os.path.basename(TARGET))
        return 0

    if not os.path.exists(SOURCE):
        print(f"Source mesh not found: {SOURCE}", file=sys.stderr)
        return 1

    print("Correcting the shear-compression mesh to the GEOS reference geometry.\n")
    report(SOURCE, f"{os.path.basename(SOURCE)}  (as generated by Cubit)")

    a, c = apply_scaling(SOURCE, TARGET)
    print(f"\n  anisotropic scaling applied: x *= {a:.12f},  y *= {c:.12f}\n")
    psi, half = report(TARGET, f"{os.path.basename(TARGET)}  (corrected)")

    ok = (
        abs(psi - TARGET_PSI_DEG) < 1e-6
        and abs(half - TARGET_HALF_LENGTH) < 1e-9
    )
    print()
    if ok:
        print("  OK — matches the GEOS reference geometry.")
        return 0
    print("  FAILED — the corrected mesh does not match the target geometry.",
          file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
